    private void btnCalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularActionPerformed
        try {
            // Validação de campos vazios
            if (txtPeso.getText().trim().isEmpty() || txtAltura.getText().trim().isEmpty() || txtIdade.getText().trim().isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Por favor, preencha todos os campos antes de calcular!", "Atenção", javax.swing.JOptionPane.WARNING_MESSAGE);
                return;
            }

            // Conversão de valores
            double peso = Double.parseDouble(txtPeso.getText().replace(",", "."));
            double altura = Double.parseDouble(txtAltura.getText().replace(",", "."));
            int idade = Integer.parseInt(txtIdade.getText().trim());

            if (peso <= 0 || altura <= 0 || idade <= 0) {
                javax.swing.JOptionPane.showMessageDialog(this, "Os valores devem ser maiores que zero!", "Dados Inválidos", javax.swing.JOptionPane.ERROR_MESSAGE);
                return;
            }

            // Cálculo do Gasto Basal (Equação de Harris-Benedict)
            double gastoBasal;
            if (rbMulher.isSelected()) {
                gastoBasal = 655 + (9.6 * peso) + (1.8 * altura) - (4.7 * idade);
            } else {
                gastoBasal = 66 + (13.7 * peso) + (5 * altura) - (6.8 * idade);
            }

            // Fator multiplicador do nível de atividade
            double fator = 1.2; // Sedentário
            int indiceAtividade = cbNivelAtividade.getSelectedIndex();

            switch (indiceAtividade) {
                case 0:
                    fator = 1.2; // Sedentário
                    break;
                case 1:
                    fator = 1.375; // Leve
                    break;
                case 2:
                    fator = 1.55; // Moderado
                    break;
                case 3:
                    fator = 1.725; // Ativo
                    break;
                case 4:
                    fator = 1.9; // Extremamente ativo
                    break;
            }

            double gastoTotal = gastoBasal * fator;

            // Atualização dos rótulos na tela
            lblGastoBasal.setText(String.format("%.2f cal", gastoBasal));
            lblGastoTotal.setText(String.format("%.2f cal", gastoTotal));

        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Informe apenas valores numéricos válidos!", "Erro de Formato", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnCalcularActionPerformed

