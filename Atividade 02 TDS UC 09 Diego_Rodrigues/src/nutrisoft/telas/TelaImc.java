    private void btnCalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularActionPerformed
        try {
            // Validação de campos vazios
            if (txtAltura.getText().trim().isEmpty() || txtPeso.getText().trim().isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Por favor, preencha todos os campos antes de calcular!", "Atenção", javax.swing.JOptionPane.WARNING_MESSAGE);
                return;
            }

            // Conversão de texto para número (substituindo vírgula por ponto)
            double altura = Double.parseDouble(txtAltura.getText().replace(",", "."));
            double peso = Double.parseDouble(txtPeso.getText().replace(",", "."));

            if (altura <= 0 || peso <= 0) {
                javax.swing.JOptionPane.showMessageDialog(this, "Altura e peso devem ser valores maiores que zero!", "Dados Inválidos", javax.swing.JOptionPane.ERROR_MESSAGE);
                return;
            }

            // Cálculo do IMC: Peso / Altura²
            double imc = peso / (altura * altura);
            lblResultado.setText(String.format("%.2f", imc));

            // Interpretação de acordo com o enunciado
            String interpretacao;
            if (imc < 18.5) {
                interpretacao = "Magreza";
            } else if (imc <= 24.9) {
                interpretacao = "Normal";
            } else if (imc <= 29.9) {
                interpretacao = "Sobrepeso";
            } else if (imc <= 39.9) {
                interpretacao = "Obesidade";
            } else {
                interpretacao = "Obesidade grave";
            }

            lblInterpretacao.setText(interpretacao);

        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Informe apenas valores numéricos válidos!", "Erro de Formato", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnCalcularActionPerformed

