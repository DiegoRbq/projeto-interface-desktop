    private void btnCalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularActionPerformed
        try {
            // 1. Validação de campo vazio
            if (txtCalorias.getText().trim().isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this, 
                    "Por favor, informe a quantidade de calorias diárias!", 
                    "Atenção", 
                    javax.swing.JOptionPane.WARNING_MESSAGE);
                return;
            }

            // 2. Conversão do valor digitado
            double calorias = Double.parseDouble(txtCalorias.getText().replace(",", "."));

            // 3. Validação de valor positivo
            if (calorias <= 0) {
                javax.swing.JOptionPane.showMessageDialog(this, 
                    "O valor de calorias deve ser maior que zero!", 
                    "Dados Inválidos", 
                    javax.swing.JOptionPane.ERROR_MESSAGE);
                return;
            }

            // 4. Cálculos da Atividade 2:
            // Carboidratos: 50% das calorias totais divididos por 4 cal/g
            double carboidratosGramas = (calorias * 0.50) / 4.0;

            // Proteínas: 25% das calorias totais divididos por 4 cal/g
            double proteinasGramas = (calorias * 0.25) / 4.0;

            // Gorduras: 25% das calorias totais divididos por 9 cal/g
            double gordurasGramas = (calorias * 0.25) / 9.0;

            // 5. Exibição dos resultados formatados
            lblCarboidratos.setText(String.format("%.2f g", carboidratosGramas));
            lblProteinas.setText(String.format("%.2f g", proteinasGramas));
            lblGorduras.setText(String.format("%.2f g", gordurasGramas));

        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, 
                "Informe um valor numérico válido para as calorias!", 
                "Erro de Formato", 
                javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnCalcularActionPerformed

