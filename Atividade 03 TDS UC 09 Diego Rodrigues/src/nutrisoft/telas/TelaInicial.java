    private void btnFinalizarConsultaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFinalizarConsultaActionPerformed
        int pos = getPosicaoSelecionada();
        if (pos >= 0) {
            Consulta c = ListaConsulta.getConsulta(pos);
            if (c.isConsultaRealizada()) {
                JOptionPane.showMessageDialog(this, "Esta consulta já foi finalizada.", "Aviso", JOptionPane.INFORMATION_MESSAGE);
            } else {
                TelaDetalhes telaDet = new TelaDetalhes(this, c);
                telaDet.setVisible(true);
            }
        }
    }//GEN-LAST:event_btnFinalizarConsultaActionPerformed

    public void atualizarTabela() {
        String[] colunas = {"Paciente", "CPF", "Telefone", "Data", "Já era paciente?", "Consulta Realizada"};
        DefaultTableModel model = new DefaultTableModel(colunas, 0);
        
        List<Consulta> lista = ListaConsulta.Listar();
        
        for (int i = 0; i < lista.size(); i++) {
            Consulta c = lista.get(i);
            String jaEra = c.isJaEraPaciente() ? "sim" : "não";
            String realizada = c.isConsultaRealizada() ? "sim" : "não";
            
            String[] linha = {
                c.getNomePaciente(),
                c.getCpf(),
                c.getTelefone(),
                c.getData(),
                jaEra,
                realizada
            };
            model.addRow(linha);
        }
        
        tblConsultas.setModel(model);
    }

    private int getPosicaoSelecionada() {
        int pos = tblConsultas.getSelectedRow();
        if (pos == -1) {
            JOptionPane.showMessageDialog(this, "Selecione uma consulta na tabela.");
        }
        return pos;
    }

    private void excluirConsulta(int pos) {
        if (pos >= 0) {
            String[] options = {"Sim", "Não"};
            int deletar = JOptionPane.showOptionDialog(
                this,
                "Tem certeza que deseja excluir esta consulta?",
                "Exclusão de Consulta",
                JOptionPane.DEFAULT_OPTION,
                JOptionPane.QUESTION_MESSAGE,
                null,
                options,
                options[0]
            );

            if (deletar == 0) {
                ListaConsulta.Excluir(pos);
                atualizarTabela();
                JOptionPane.showMessageDialog(this, "Consulta excluída com sucesso!");
            } else {
                tblConsultas.clearSelection();
            }
        }
    }
