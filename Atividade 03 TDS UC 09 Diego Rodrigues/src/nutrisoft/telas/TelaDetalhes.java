    private void btnFinalizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFinalizarActionPerformed
   boolean realizada = chkConsultaRealizada.isSelected();
        String receita = txtReceita.getText().trim();

        if (!realizada) {
            JOptionPane.showMessageDialog(this, "Para finalizar a consulta, marque a opção 'Consulta Realizada'.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        if (receita.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Preencha o campo de receita e observações antes de finalizar.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (this.consulta != null) {
            this.consulta.setConsultaRealizada(true);
            this.consulta.setReceitaObservacoes(receita);
        }

        JOptionPane.showMessageDialog(this, "Consulta finalizada com sucesso!");

        if (this.telaInicial != null) {
            this.telaInicial.atualizarTabela();
        }

        this.dispose();
    }//GEN-LAST:event_btnFinalizarActionPerformed

