    private void btnCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCadastrarActionPerformed
      String nome = txtNome.getText().trim();
        String telefone = txtTelefone.getText().trim();
        String cpf = txtCpf.getText().trim();
        String data = txtData.getText().trim();
        boolean jaPaciente = chkJaPaciente.isSelected();

        // 1. Validação de campos vazios
        if (nome.isEmpty() || telefone.isEmpty() || cpf.isEmpty() || data.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Todos os campos devem ser preenchidos.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // 2. Cria o objeto Consulta (com os 5 parâmetros corretos do construtor)
        Consulta novaConsulta = new Consulta(nome, telefone, cpf, data, jaPaciente);

        // 3. Adiciona à lista em memória (usando o nome correto do método com A maiúsculo)
        ListaConsulta.Adicionar(novaConsulta);

        // 4. Mensagem de sucesso
        JOptionPane.showMessageDialog(this, "Consulta cadastrada com sucesso!");

        // 5. Atualiza a tabela na Tela Inicial
        if (this.telaInicial != null) {
            this.telaInicial.atualizarTabela();
        }

        // 6. Fecha a janela de cadastro
        this.dispose();
    }//GEN-LAST:event_btnCadastrarActionPerformed

